class Stream(C.Structure):
    _fields_ = [("channels", C.c_uint16), ("frames", C.c_uint16),
                ("rate", C.c_uint32), ("format", C.c_uint8),
                ("full_bits", C.c_uint8), ("alignment", C.c_uint8),
                ("valid_bits", C.c_uint8)]

class Platform(C.Structure):
    _fields_ = [("present", C.c_uint8), ("detection", C.c_uint8),
                ("codename_length", C.c_uint8), ("codename", C.c_char * 33)]

class Gain(C.Structure):
    _fields_ = [("present", C.c_uint8), ("encoding", C.c_uint8),
                ("availability", C.c_uint8), ("provenance", C.c_uint8),
                ("applied_to_pcm", C.c_uint8), ("mic_channels", C.c_uint16),
                ("present_mask", C.c_uint32), ("coefficients", C.c_int64 * 16)]

class Descriptor(C.Structure):
    _fields_ = [("stream_flags", C.c_uint32), ("mic_bytes", C.c_uint32),
                ("ref_bytes", C.c_uint32), ("mic", Stream), ("ref", Stream),
                ("platform", Platform), ("gain", Gain)]

LIB.cfg2_decode.argtypes = [C.c_void_p, C.c_size_t, C.POINTER(Descriptor)]
LIB.cfg2_decode.restype = C.c_int
LIB.cfg2_error_string.argtypes = [C.c_int]
LIB.cfg2_error_string.restype = C.c_char_p

def decode(data):
    output = Descriptor()
    C.memset(C.byref(output), 0xa5, C.sizeof(output))
    buf = C.create_string_buffer(bytes(data), len(data)) if data else C.create_string_buffer(1)
    result = LIB.cfg2_decode(buf, len(data), C.byref(output))
    if result:
        # Verify failure never leaks partially populated values, including padding.
        assert bytes(output) == bytes(C.sizeof(output)), (result, data[:16].hex())
    return result, output

def checked(data):
    status, out = decode(data)
    if status != 0:
        raise AssertionError(f"unexpected decoder rejection {status}: {LIB.cfg2_error_string(status)}")
    return out

def fields(s):
    return s.channels, s.frames, s.rate, s.format, s.full_bits, s.alignment, s.valid_bits

def pack_stream(ch=1, frames=320, rate=16000, fmt=1, full=15, align=0, valid=16, reserved=0):
    return STREAM.pack(ch, frames, rate, fmt, full, align, valid, reserved)

def packet(tlvs, flags=1):
    raw = b"".join(TLV.pack(typ, fl, len(v)) + v for typ, fl, v in tlvs)
    return HDR.pack(b"CFG2", 2, 16, 16 + len(raw), flags) + raw

def unpack_tlvs(data):
    pos, result = 16, []
    while pos < len(data):
        typ, fl, n = TLV.unpack_from(data, pos)
        pos += 8
        result.append((typ, fl, bytes(data[pos:pos+n])))
        pos += n
    assert pos == len(data)
    return result

def stream_packet(mic=None, ref=None, flags=1):
    return packet([(1, 1, pack_stream() if mic is None else mic),
                   (2, 1, bytes(16) if ref is None else ref)], flags)

def platform(name=b"athena", detection=1, version=1, reserved=0):
    return bytes([version, detection, len(name), reserved]) + name

def gain(ch=4, mask=15, availability=1, encoding=1, provenance=1,
         applied=0, version=1, reserved=0, values=None):
    if values is None:
        values = [0x40000000] * ch
    return struct.pack("<HBBBBHII", version, encoding, availability, provenance,
                       applied, ch, mask, reserved) + (
        b"" if availability == 0 else b"".join(struct.pack("<q", v) for v in values))

def with_platform(value, base="athena_4mic_2ref"):
    tlvs = unpack_tlvs((FIXTURES / (base + ".cfg2")).read_bytes())
    return packet(tlvs + [(3, 0, value)], 7)

def with_gain(value):
    raw = (FIXTURES / "athena_4mic_2ref.cfg2").read_bytes()
    return packet(unpack_tlvs(raw) + [(0x101, 0, value)], 7)

def mutate(data, pos, replacement):
    b = bytearray(data)
    b[pos] = replacement
    return bytes(b)

class Cfg2Tests(unittest.TestCase):
    def assertRejected(self, data, message=""):
        status, _ = decode(data)
        self.assertNotEqual(status, 0, message)

    def test_01_pinned_six_hashes_and_independent_decoding(self):
        for name, expected in EXPECT.items():
            with self.subTest(name=name):
                data = (FIXTURES / (name + ".cfg2")).read_bytes()
                self.assertEqual(hashlib.sha256(data).hexdigest(), HASHES[name])
                self.assertEqual(len(data), struct.unpack_from("<I", data, 8)[0])
                self.assertEqual([x[0] for x in unpack_tlvs(data)],
                                 sorted(x[0] for x in unpack_tlvs(data)))
                out = checked(data)
                self.assertEqual((out.stream_flags, fields(out.mic), fields(out.ref),
                                  out.mic_bytes, out.ref_bytes), expected[:5])
                exp_platform, exp_gain = expected[5:]
                self.assertEqual(bool(out.platform.present), exp_platform is not None)
                if exp_platform:
                    self.assertEqual((out.platform.detection,
                                      out.platform.codename[:out.platform.codename_length].decode()),
                                     exp_platform)
                    self.assertEqual(out.platform.codename[out.platform.codename_length:], b"")
                self.assertEqual(bool(out.gain.present), exp_gain is not None)
                if exp_gain:
                    availability, mask, values = exp_gain
                    self.assertEqual((out.gain.availability, out.gain.present_mask),
                                     (availability, mask))
                    self.assertEqual((out.gain.encoding, out.gain.provenance, out.gain.applied_to_pcm),
                                     (1 if availability else 0, 1 if availability else 0, 0))
                    self.assertEqual(out.gain.mic_channels, out.mic.channels)
                    self.assertEqual(list(out.gain.coefficients), list(values) + [0] * (16-len(values)))

    def test_02_exhaustive_prefix_truncations_and_extra_bytes(self):
        for name in HASHES:
            data = (FIXTURES / (name + ".cfg2")).read_bytes()
            for n in range(len(data)):
                with self.subTest(name=name, truncation=n):
                    self.assertRejected(data[:n])
            self.assertRejected(data + b"\0")
        # Truncate every TLV header/body at all cut points, preserving new total.
        raw = (FIXTURES / "athena_confirmed_complete_4mic.cfg2").read_bytes()
        for n in range(16, len(raw)):
            b = bytearray(raw[:n])
            struct.pack_into("<I", b, 8, n)
            # Core-only (64) and core+platform (82) are independently valid:
            # the schema explicitly permits omitted optional TLVs.
            if n in (64, 82):
                checked(b)
            else:
                self.assertRejected(b, f"reframed truncation at {n}")

    def test_03_header_length_flags_and_legacy(self):
        good = (FIXTURES / "generic_1mic_noref.cfg2").read_bytes()
        for off, fmt, values in [
            (4, "<H", [0, 1, 3, 65535]),
            (6, "<H", [0, 15, 17, 40, 65535]),
            (8, "<I", [0, 15, 16, 17, 8193, 0xffffffff]),
            (12, "<I", [0, 2, 3, 5, 6, 8, 0xffffffff])]:
            for value in values:
                b = bytearray(good)
                struct.pack_into(fmt, b, off, value)
                self.assertRejected(b, f"header off={off} value={value}")
        for off in range(4):
            self.assertRejected(mutate(good, off, 0))
        # Old schema version 2 with header_bytes=40 must not be accepted.
        old = (Path(__file__).resolve().parent / "rejected_fixed_cfg2.bin").read_bytes()
        self.assertEqual(len(old), 40)
        self.assertRejected(old)

    def test_04_tlv_order_duplicates_unknown_and_boundaries(self):
        raw = (FIXTURES / "athena_confirmed_complete_4mic.cfg2").read_bytes()
        tags = unpack_tlvs(raw)
        self.assertEqual(len(tags), 4)
        for typ in [1, 2, 3, 0x101]:
            self.assertRejected(packet(tags + [next(t for t in tags if t[0] == typ)], 7),
                                f"duplicate {typ}")
        for order in [(tags[1], tags[0]), (tags[0], tags[2], tags[1]),
                      (tags[0], tags[1], tags[3], tags[2])]:
            self.assertRejected(packet(list(order), 7))
        for typ in [0, 0xffff]:
            self.assertRejected(packet([(typ, 0, b"")] + tags, 7))
        for typ in [0x100, 0x102, 0x300, 0xfffe]:
            base = [(1, 1, pack_stream()), (2, 1, bytes(16))]
            self.assertEqual(checked(packet(base + [(typ, 0, b"ignored")])).mic_bytes, 640)
            self.assertRejected(packet(base + [(typ, 1, b"ignored")]))
        self.assertRejected(packet(tags[:1], 7))
        self.assertRejected(packet(tags[1:], 7))
        for typ in [1, 2]:
            new = [(t, 0 if t == typ else f, v) for t, f, v in tags]
            self.assertRejected(packet(new, 7))
        for typ in [3, 0x101]:
            new = [(t, 1 if t == typ else f, v) for t, f, v in tags]
            self.assertRejected(packet(new, 7))
        for f in [2, 3, 4, 0xffff]:
            self.assertRejected(packet([(1, 1, pack_stream()),
                                        (2, 1, bytes(16)), (0x200, f, b"x")]))
        base = [(1, 1, pack_stream()), (2, 1, bytes(16))]
        self.assertEqual(len(unpack_tlvs(packet(base + [(i+0x200, 0, b"") for i in range(62)]))), 64)
        checked(packet(base + [(i+0x200, 0, b"") for i in range(62)]))
        self.assertRejected(packet(base + [(i+0x200, 0, b"") for i in range(63)]))
        big = packet(base + [(0x200, 0, bytes(8192-64-8))])
        self.assertEqual(len(big), 8192)
        checked(big)
        self.assertRejected(big + b"x")
        self.assertRejected(packet(base + [(0x200, 0, bytes(8193-64-8))]))
        for typ in [1, 2, 3, 0x101, 0x200]:
            target = next((i for i,x in enumerate(tags) if x[0] == typ), None)
            if target is None:
                continue
            corrupted = bytearray(raw)
            off = 16 + sum(8 + len(t[2]) for t in tags[:target]) + 4
            struct.pack_into("<I", corrupted, off, 0xffffffff)
            self.assertRejected(corrupted, f"forged length {typ}")

    def test_05_streams_and_payload_limit(self):
        valid = [(1, 160, 8000, 1, 1, 0, 2),
                 (16, 3840, 192000, 2, 31, 1, 24),
                 (1, 320, 16000, 2, 23, 0, 24),
                 (4, 960, 48000, 2, 31, 1, 24)]
        for values in valid:
            ch, frames, rate, fmt, full, align, bits = values
            expected = frames * ch * (fmt*2)
            self.assertEqual(checked(stream_packet(pack_stream(*values))).mic_bytes, expected)
        invalid = [
            dict(ch=0), dict(ch=17), dict(ch=65535),
            dict(frames=319), dict(frames=0), dict(rate=0),
            dict(rate=7950), dict(rate=192050), dict(rate=16001),
            dict(fmt=0), dict(fmt=3), dict(full=0), dict(full=16),
            dict(align=2), dict(valid=0), dict(valid=1), dict(valid=17),
            dict(valid=33), dict(reserved=1), dict(reserved=0xffffffff),
            dict(fmt=2, valid=16, full=31), dict(fmt=2, align=1, full=15),
        ]
        for kwargs in invalid:
            self.assertRejected(stream_packet(pack_stream(**kwargs)), str(kwargs))
        self.assertRejected(stream_packet(bytes(15)))
        self.assertRejected(stream_packet(bytes(17)))
        self.assertRejected(stream_packet(ref=pack_stream(ch=0), flags=7))
        self.assertRejected(stream_packet(ref=pack_stream(ch=9), flags=7))
        self.assertRejected(stream_packet(ref=pack_stream(ch=1, reserved=1), flags=7))
        self.assertRejected(stream_packet(ref=pack_stream(ch=1), flags=1))
        self.assertRejected(stream_packet(flags=7))
        # REF absent must be exactly sixteen zero bytes, not just channels zero.
        for index in range(2, 16):
            ref = bytearray(16)
            ref[index] = 1
            self.assertRejected(stream_packet(ref=ref))
        # Both individual and sum limits, hardware REF with same 20ms sampling.
        mic = pack_stream(ch=16, frames=3840, rate=192000, fmt=2, full=31, align=1, valid=24)
        ref = pack_stream(ch=8, frames=3840, rate=192000, fmt=2, full=31, align=1, valid=24)
        self.assertEqual(checked(stream_packet(mic)).mic_bytes, 245760)
        self.assertRejected(stream_packet(mic, ref, 7))
        mic = pack_stream(ch=16, frames=3840, rate=192000, fmt=2, full=31, align=1, valid=24)
        ref = pack_stream(ch=8, frames=3840, rate=192000, fmt=1, full=15, align=0, valid=16)
        self.assertRejected(stream_packet(mic, ref, 7))

    def test_06_platform_strict_schema(self):
        for name in [b"a", b"abc_123-z", b"z"*32, b"rook", b"completely_unknown"]:
            data = with_platform(platform(name))
            out = checked(data)
            self.assertEqual(out.platform.codename, name)
        for name in [b"", b"a"*33, b"Athena", b"dot.x", b"x y", b"x/y",
                     b"\0", b"\xff", b"\xc3\xa9", b"x\n", b"x\x7f"]:
            self.assertRejected(with_platform(platform(name)), repr(name))
        for detection in [0, 3, 255]:
            self.assertRejected(with_platform(platform(detection=detection)))
        for version in [0, 2, 255]:
            self.assertRejected(with_platform(platform(version=version)))
        self.assertRejected(with_platform(platform(reserved=1)))
        self.assertRejected(with_platform(platform(b"athena") + b"x"))
        self.assertRejected(with_platform(platform(b"athena")[:-1]))
        self.assertRejected(with_platform(bytes([1, 1, 33, 0]) + b"a"*33))
        self.assertRejected(with_platform(bytes([1, 1, 0, 0])))
        self.assertRejected(with_platform(b"\x01\x01\x01"))
        self.assertRejected(with_platform(b"\x01\x01\x01\0athena\x00"))
        # Known optional, malformed = reject, not ignored.
        self.assertRejected(packet([(1, 1, pack_stream()), (2, 1, bytes(16)),
                                    (3, 0, b"invalid")]))
        self.assertRejected(packet([(1, 1, pack_stream()), (2, 1, bytes(16)),
                                    (3, 1, platform())]))

    def test_07_gain_schema_masks_q30_and_16mic_boundary(self):
        self.assertEqual(checked(with_gain(gain())).gain.present_mask, 15)
        self.assertEqual(checked(with_gain(gain(availability=2, mask=5,
                         values=[0x40000000,0,1,0]))).gain.coefficients[2], 1)
        self.assertEqual(checked(with_gain(gain(ch=4, mask=15,
                         values=[1,0x7fffffff,0x40000000,1]))).gain.coefficients[1], 0x7fffffff)
        self.assertEqual(checked(with_gain(gain(ch=4, mask=0, availability=0,
                         encoding=0, provenance=0, values=[]))).gain.availability, 0)
        mic16 = pack_stream(ch=16)
        default16 = [(1, 1, mic16), (2, 1, bytes(16))]
        gain16 = gain(ch=16, mask=0xffff, values=[i+1 for i in range(16)])
        out = checked(packet(default16 + [(0x101, 0, gain16)]))
        self.assertEqual((out.gain.present_mask, list(out.gain.coefficients)),
                         (0xffff, list(range(1,17))))
        partial16 = gain(ch=16, mask=0x8001, availability=2,
                         values=[1]+[0]*14+[0x7fffffff])
        self.assertEqual(checked(packet(default16+[(0x101, 0, partial16)])).gain.coefficients[15],
                         0x7fffffff)
        self.assertRejected(packet(default16+[(0x101, 0, gain(ch=16,mask=0x10000,
                          availability=2, values=[1]*16))]))
        negative = [
            gain(ch=3), gain(ch=0), gain(ch=17),
            gain(mask=16), gain(mask=0), gain(mask=15, availability=2),
            gain(mask=0, availability=2),
            gain(availability=0), gain(availability=3),
            gain(encoding=0), gain(encoding=2), gain(provenance=0), gain(provenance=2),
            gain(applied=1), gain(applied=255), gain(version=0), gain(version=2),
            gain(reserved=1), gain(reserved=0xffffffff),
            gain(values=[0,1,1,1]), gain(values=[-1,1,1,1]),
            gain(values=[0x80000000,1,1,1]), gain(values=[2**63-1,1,1,1]),
            gain(mask=5,availability=2,values=[1,1,1,0]),
            gain(mask=5,availability=2,values=[1,0,1,1]),
            gain(mask=3,availability=1,values=[1]*4),
        ]
        for index, value in enumerate(negative):
            self.assertRejected(with_gain(value), f"gain negative #{index}")
        self.assertRejected(with_gain(gain()[:15]))
        self.assertRejected(with_gain(gain()[:-1]))
        self.assertRejected(with_gain(gain()+b"x"))
        self.assertRejected(with_gain(gain(mask=0, availability=0, encoding=0,
                                          provenance=0, values=[])+b"\0"))
        self.assertRejected(with_gain(b"\x01\x00"))
        # Wrong schema and zero/signed-overflow values must never be interpreted as unity.
        bad = bytearray(gain())
        struct.pack_into("<Q", bad, 16, 0xffffffffffffffff)
        self.assertRejected(with_gain(bad))

    def test_08_ownership_determinism_null_and_fuzzlike(self):
        original = bytearray((FIXTURES / "athena_confirmed_complete_4mic.cfg2").read_bytes())
        status, out = decode(original)
        self.assertEqual(status, 0)
        snapshot = bytes(out)
        original[:] = b"\xff" * len(original)
        self.assertEqual(bytes(out), snapshot)  # fixed arrays owned by caller
        seed = (FIXTURES / "unknown_inferred_partial_4mic.cfg2").read_bytes()
        first = bytes(checked(seed))
        for _ in range(10):
            self.assertEqual(bytes(checked(seed)), first)
        invalid = Descriptor()
        C.memset(C.byref(invalid), 0xa5, C.sizeof(invalid))
        self.assertNotEqual(LIB.cfg2_decode(None, 100, C.byref(invalid)), 0)
        self.assertEqual(bytes(invalid), bytes(C.sizeof(invalid)))
        ptr = C.create_string_buffer(seed)
        self.assertNotEqual(LIB.cfg2_decode(ptr, len(seed), None), 0)
        rand = random.Random(0xC0C2026)
        corpus = [((FIXTURES / (x+".cfg2")).read_bytes()) for x in HASHES]
        for i in range(2500):
            b = bytearray(corpus[i % len(corpus)])
            for _ in range(rand.randint(1, 7)):
                offset = rand.randrange(len(b))
                b[offset] = rand.getrandbits(8)
            status, _ = decode(b)
            self.assertGreaterEqual(status, 0)
            self.assertLessEqual(status, 9)
            if status == 0:
                self.assertEqual(bytes(checked(b)), bytes(decode(b)[1]))
        self.assertRejected(b"\xff" * 8192)
        self.assertRejected(b"\0" * 8192)

